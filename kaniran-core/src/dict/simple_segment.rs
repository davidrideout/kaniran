    // tests.lisp:33 (assert-segment) — :gap word-infos map to GAP, others
    // to their text.
    fn segmentation(word_info_list: &[WordInfo]) -> Vec<&str> {
        word_info_list
            .iter()
            .map(|wi| {
                if wi.kind == WordInfoType::Gap {
                    GAP
                } else {
                    wi.text.as_str()
                }
            })
            .collect()
    }

